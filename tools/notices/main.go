// Command notices writes THIRD_PARTY_NOTICES.md for the Go modules linked into the shipped binaries
// (FR-R07, FR-S08). Offline: it reads the module cache that `go build` already filled.
//
//	go run ./tools/notices -o THIRD_PARTY_NOTICES.md
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

type module struct {
	Path, Version, Dir string
	Main               bool
	Replace            *module
}

var licenseFiles = regexp.MustCompile(`(?i)^(licen[cs]e|copying|notice)(\.(md|txt|rst))?$`)

// classify names the license from its text (good enough for a notice index; the full text is included).
func classify(text string) string {
	t := strings.ToLower(text)
	switch {
	case strings.Contains(t, "apache license") && strings.Contains(t, "version 2.0"):
		return "Apache-2.0"
	case strings.Contains(t, "mozilla public license") && strings.Contains(t, "2.0"):
		return "MPL-2.0"
	case strings.Contains(t, "permission is hereby granted, free of charge"):
		return "MIT"
	case strings.Contains(t, "permission to use, copy, modify, and/or distribute"):
		return "ISC"
	case strings.Contains(t, "redistribution and use in source and binary forms"):
		if strings.Contains(t, "neither the name") || strings.Contains(t, "endorse or promote") {
			return "BSD-3-Clause"
		}
		return "BSD-2-Clause"
	case strings.Contains(t, "cc0 1.0") || strings.Contains(t, "creative commons legal code"):
		return "CC0-1.0"
	case strings.Contains(t, "gnu lesser general public license"):
		return "LGPL"
	case strings.Contains(t, "gnu general public license"):
		return "GPL"
	}
	return "see text"
}

func main() {
	out := flag.String("o", "", "output file (default stdout)")
	flag.Parse()
	// only modules that end up in the binaries (not test-only dependencies)
	cmd := exec.Command("go", "list", "-deps", "-f", "{{with .Module}}{{.Path}}{{end}}", "./cmd/...")
	b, err := cmd.Output()
	if err != nil {
		fmt.Fprintln(os.Stderr, "go list -deps:", err)
		os.Exit(1)
	}
	used := map[string]bool{}
	for _, l := range strings.Split(string(b), "\n") {
		if l = strings.TrimSpace(l); l != "" {
			used[l] = true
		}
	}
	lm := exec.Command("go", "list", "-m", "-json", "all")
	mb, err := lm.Output()
	if err != nil {
		fmt.Fprintln(os.Stderr, "go list -m:", err)
		os.Exit(1)
	}
	dec := json.NewDecoder(bytes.NewReader(mb))
	var mods []module
	for {
		var m module
		if err := dec.Decode(&m); err == io.EOF {
			break
		} else if err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
		if m.Main || !used[m.Path] {
			continue
		}
		if m.Replace != nil {
			m.Dir = m.Replace.Dir
		}
		mods = append(mods, m)
	}
	sort.Slice(mods, func(i, j int) bool { return mods[i].Path < mods[j].Path })

	var w bytes.Buffer
	fmt.Fprintln(&w, "# Third-party notices")
	fmt.Fprintln(&w)
	fmt.Fprintln(&w, "Go modules linked into the Continuum binaries (generated by `go run ./tools/notices`). Optional system")
	fmt.Fprintln(&w, "components (macFUSE, WinFsp, FUSE-T, Samba, mergerfs) are not bundled — see docs/optional-dependencies.md.")
	fmt.Fprintln(&w)
	fmt.Fprintln(&w, "| Module | Version | License |")
	fmt.Fprintln(&w, "|---|---|---|")
	type entry struct{ name, text string }
	var texts []entry
	missing := 0
	for _, m := range mods {
		lic, text := "not found", ""
		if ents, err := os.ReadDir(m.Dir); err == nil {
			for _, e := range ents {
				if !e.IsDir() && licenseFiles.MatchString(e.Name()) {
					if tb, err := os.ReadFile(filepath.Join(m.Dir, e.Name())); err == nil {
						text += strings.TrimSpace(string(tb)) + "\n\n"
						if lic == "not found" {
							lic = classify(string(tb))
						}
					}
				}
			}
		}
		if text == "" {
			missing++
		}
		fmt.Fprintf(&w, "| %s | %s | %s |\n", m.Path, m.Version, lic)
		texts = append(texts, entry{m.Path + " " + m.Version, text})
	}
	fmt.Fprintln(&w)
	for _, t := range texts {
		if t.text == "" {
			continue
		}
		fmt.Fprintf(&w, "## %s\n\n```text\n%s```\n\n", t.name, t.text)
	}
	if *out == "" {
		os.Stdout.Write(w.Bytes())
	} else if err := os.WriteFile(*out, w.Bytes(), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	fmt.Fprintf(os.Stderr, "notices: %d modules, %d without a license file\n", len(mods), missing)
	if missing > 0 {
		os.Exit(2) // a release must not ship a dependency whose license is unknown
	}
}
