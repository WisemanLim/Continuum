export type Lang = "ko" | "en";
export const dicts: Record<Lang, Record<Key, string>> = { en, ko };

export const LangContext = createContext<Lang>("ko");

export function useT() {
  const lang = useContext(LangContext);
  return (k: Key, vars?: Record<string, string | number>) => {
    let s: string = dicts[lang][k] ?? en[k] ?? k;
    if (vars) for (const [n, v] of Object.entries(vars)) s = s.replace(`{${n}}`, String(v));
    return s;
  };
}
